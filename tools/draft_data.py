#!/usr/bin/env python3
"""Generate the draft's data image (step 4 of the "everything compiles" plan).

    ILB.exe  ->  draft/build/ILB_image.bin   bytes of the initialised data sections, as loaded
                 draft/build/src/_image.c    ILB_image[] (the whole image, zero-filled), ILB_image_init()
                 draft/build/fixups.json     the same pointer fix-ups, for reading

Every global in the draft is a macro into ILB_image at its original address (tools/draft_fix.py), so the
image keeps the binary's layout. Pointers stored in the data are listed by the exe's relocation table:
a pointer to data is moved by the distance between ILB_image and the original load address, a pointer to a
function is replaced by the address of the recompiled function.
"""
import json
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXE = os.environ.get("ILB_EXE", os.path.join(os.environ.get("ILB_GAME", os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "game")), "ILB.exe"))
OUT = os.path.join(ROOT, "draft", "build")

exe = open(EXE, "rb").read()
pe = struct.unpack_from("<I", exe, 0x3C)[0]
assert exe[pe:pe + 4] == b"PE\0\0"
num_sections, = struct.unpack_from("<H", exe, pe + 6)
optional_size, = struct.unpack_from("<H", exe, pe + 20)
optional = pe + 24
image_base, = struct.unpack_from("<I", exe, optional + 28)
image_size, = struct.unpack_from("<I", exe, optional + 56)
reloc_rva, reloc_size = struct.unpack_from("<II", exe, optional + 96 + 5 * 8)

sections = []
for i in range(num_sections):
    o = optional + optional_size + i * 40
    name = exe[o:o + 8].rstrip(b"\0").decode()
    vsize, rva, raw_size, raw = struct.unpack_from("<IIII", exe, o + 8)
    sections.append({"name": name, "rva": rva, "vsize": vsize, "raw": raw, "raw_size": raw_size})


def section_of(rva):
    for s in sections:
        if s["rva"] <= rva < s["rva"] + max(s["vsize"], s["raw_size"]):
            return s
    return None


def file_offset(rva):
    s = section_of(rva)
    return s["raw"] + (rva - s["rva"])


# initialised data: everything the loader copies from the file, except code
# ... and the code section too: the compiler keeps switch index tables among the code, and the draft
# reads them as data (byte_52FB8C in the room set-up). The code bytes themselves are never executed.
data_sections = [s for s in sections if s["name"] in (".text", ".rdata", ".data")]
first = min(s["rva"] for s in data_sections)
last = max(s["rva"] + min(s["raw_size"], s["vsize"]) for s in data_sections)
blob = bytearray(last - first)
for s in data_sections:
    size = min(s["raw_size"], s["vsize"])
    blob[s["rva"] - first:s["rva"] - first + size] = exe[s["raw"]:s["raw"] + size]
open(os.path.join(OUT, "ILB_image.bin"), "wb").write(blob)

# function address -> name, from the draft's own definitions
functions = {}
for name in sorted(os.listdir(os.path.join(OUT, "src"))):
    if not name.endswith(".c") or name.startswith("_"):
        continue
    text = open(os.path.join(OUT, "src", name)).read()
    for m in re.finditer(r"^//----- \(([0-9A-F]{8})\) -+\n(?://[^\n]*\n)*([^\n;{}]*?\b([A-Za-z_$][\w$]*)\([^;{}]*\))\n\{", text, re.M):
        functions[int(m.group(1), 16)] = re.sub(r"__regs$", "", m.group(3))    # the pointer entry, see tools/draft_fix.py

# relocation table: every 32-bit slot that holds an absolute address
text_section = next(s for s in sections if s["name"] == ".text")
slots, o, end = [], file_offset(reloc_rva), file_offset(reloc_rva) + reloc_size
while o < end:
    page, size = struct.unpack_from("<II", exe, o)
    if size == 0:
        break
    for entry, in struct.iter_unpack("<H", exe[o + 8:o + size]):
        if entry >> 12 == 3:
            slots.append(page + (entry & 0xFFF))
    o += size

data_fixups, code_fixups, unresolved, in_code = [], [], [], 0
for rva in slots:
    s = section_of(rva)
    if s is None or s["name"] not in (".rdata", ".data"):
        in_code += 1                        # an address inside an instruction; the code is recompiled
        continue
    if not (first <= rva < last):
        continue
    target, = struct.unpack_from("<I", blob, rva - first)
    target_section = section_of(target - image_base)
    if target_section is text_section:
        if target in functions:
            code_fixups.append((rva, functions[target]))
        else:
            unresolved.append((rva, target))
    else:
        data_fixups.append(rva)

with open(os.path.join(OUT, "src", "_image.c"), "w") as f:
    f.write("// The data image of the mechanical draft, generated by tools/draft_data.py. Do not edit.\n")
    f.write('#include "ILB_draft_decls.h"\n\n')
    f.write("#define ILB_IMAGE_BASE  0x%X\n#define ILB_IMAGE_SIZE  0x%X\n#define ILB_DATA_FIRST  0x%X\n#define ILB_DATA_SIZE   0x%X\n\n" % (
        image_base, image_size, first, len(blob)))
    f.write("char ILB_image[ ILB_IMAGE_SIZE ];\n\n")
    f.write("// the initialised part of .rdata and .data, byte for byte as the loader maps it\n")
    f.write("// (C symbols carry a leading underscore on 32-bit Windows and none on Linux)\n")
    f.write("#define ILB_STRING2( x ) #x\n#define ILB_STRING( x ) ILB_STRING2( x )\n")
    f.write("#ifdef _WIN32\n#define ILB_RODATA \".rdata\"\n#else\n#define ILB_RODATA \".rodata\"\n#endif\n")
    f.write('__asm__( ".section " ILB_RODATA "\\n" ILB_STRING( __USER_LABEL_PREFIX__ ) "ILB_image_data:\\n.incbin \\"ILB_image.bin\\"\\n.text\\n" );\n')
    f.write("extern const char ILB_image_data[];\n\n")
    f.write("// slots holding a pointer to data: moved by the distance between ILB_image and the original base\n")
    f.write("static const unsigned int data_fixups[] =\n{\n")
    for i in range(0, len(data_fixups), 12):
        f.write("    " + ", ".join("0x%X" % r for r in data_fixups[i:i + 12]) + ",\n")
    f.write("};\n\n// slots holding a pointer to a function: set to the recompiled function\n")
    f.write("static const struct { unsigned int slot; void *function; } code_fixups[] =\n{\n")
    for rva, name in code_fixups:
        f.write("    { 0x%X, (void *)%s },\n" % (rva, name))
    f.write("};\n\n")
    f.write("// slots pointing into code that is not the start of a draft function (C runtime, jump tables):\n")
    for rva, target in unresolved:
        f.write("//    slot %08X -> %08X\n" % (image_base + rva, target))
    f.write("""
void ILB_image_init( void )
{
    memcpy( ILB_image + ILB_DATA_FIRST, ILB_image_data, ILB_DATA_SIZE );
    for ( unsigned int i = 0; i < sizeof( data_fixups ) / sizeof( data_fixups[ 0 ] ); i++ )
        *(unsigned int *)( ILB_image + data_fixups[ i ] ) += (unsigned int)ILB_image - ILB_IMAGE_BASE;
    for ( unsigned int i = 0; i < sizeof( code_fixups ) / sizeof( code_fixups[ 0 ] ); i++ )
        *(void **)( ILB_image + code_fixups[ i ].slot ) = code_fixups[ i ].function;
}
""")

json.dump({"data": data_fixups, "code": code_fixups, "unresolved": unresolved},
          open(os.path.join(OUT, "fixups.json"), "w"))
print("image: base %X, size %.1f MB, initialised data %X..%X (%.1f MB)" % (
    image_base, image_size / 1e6, image_base + first, image_base + last, len(blob) / 1e6))
print("relocation slots: %d (%d inside code, ignored)" % (len(slots), in_code))
print("   pointers to data: %d, pointers to draft functions: %d, pointers into other code: %d" % (
    len(data_fixups), len(code_fixups), len(unresolved)))
targets = {}
for rva, target in unresolved:
    targets.setdefault(target, []).append(rva)
for target, where in sorted(targets.items())[:25]:
    print("      %08X  (%d slot%s, first at %08X)" % (target, len(where), "" if len(where) == 1 else "s", image_base + where[0]))
