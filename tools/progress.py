#!/usr/bin/env python3
"""Write PROGRESS.md: per source file, how many functions exist, are named, and are written in src/."""
import collections
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
index = json.load(open(os.path.join(ROOT, "dump", "index.json")))
names = json.load(open(os.path.join(ROOT, "db", "names.json")))
files = json.load(open(os.path.join(ROOT, "db", "files.json")))

# the mechanical draft (tools/draft_fix.py): which functions it defines
manifest_path = os.path.join(ROOT, "draft", "build", "manifest.json")
manifest = json.load(open(manifest_path)) if os.path.exists(manifest_path) else {}
RUNTIME_TAIL = 0x582B00
known = {"%08X" % fn["ea"] for fn in index}
# functions found after the index was made (tools/ida/add_functions.py) are in the draft only
index = index + [{"ea": int(k, 16), "lib": False, "size": 0} for k in sorted(manifest) if k not in known]

rows = collections.defaultdict(lambda: collections.Counter())
order = {}
for fn in index:
    key = "%08X" % fn["ea"]
    loc = files.get(key)
    if fn["lib"] or fn["ea"] >= RUNTIME_TAIL:
        bucket = "(library / CRT)"
    elif not loc:
        bucket = "(no file known)"
    elif loc["file"]:
        bucket = loc["file"]
    else:
        bucket = "(between two files)"
    order.setdefault(bucket, fn["ea"])
    row = rows[bucket]
    row["functions"] += 1
    row["bytes"] += fn["size"]
    conf = names.get(key, {}).get("confidence")
    if conf in ("high", "medium", "manual"):
        row["named"] += 1
    elif conf == "low":
        row["guessed"] += 1
    name = names.get(key, {}).get("name")
    src = os.path.join(ROOT, "src", bucket)
    written = False
    if name and conf in ("high", "medium", "manual") and os.path.exists(src):
        if re.search(r"\b%s\s*\(" % re.escape(name), open(src).read()):
            row["written"] += 1
            written = True
    if bucket != "(library / CRT)" and not written:
        row["draft" if key in manifest else "missing"] += 1

total = collections.Counter()
lines = ["# Progress", "",
         "Generated by `tools/progress.py`. Named = name recovered from asserts (certain or by position); "
         "guessed = low-confidence name; written = named function present in `src/<file>`; draft = only in the "
         "mechanical draft (`draft/build/src`, IDA output made compilable by `tools/draft_fix.py`); missing = in neither.", "",
         "| Source file | Functions | Bytes | Named | Guessed | Unnamed | Written | Draft | Missing |",
         "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
for bucket in sorted(rows, key=lambda b: (b.startswith("("), order[b])):
    r = rows[bucket]
    unnamed = r["functions"] - r["named"] - r["guessed"]
    lines.append("| %s | %d | %d | %d | %d | %d | %d | %d | %d |" % (
        bucket, r["functions"], r["bytes"], r["named"], r["guessed"], unnamed, r["written"], r["draft"], r["missing"]))
    total.update(r)
lines.append("| **Total** | %d | %d | %d | %d | %d | %d | %d | %d |" % (
    total["functions"], total["bytes"], total["named"], total["guessed"],
    total["functions"] - total["named"] - total["guessed"], total["written"], total["draft"], total["missing"]))

# hand-written functions whose parameter count differs from the draft's: the draft's callers pass the
# arguments IDA saw (often including registers that are not real parameters), so these call sites need
# attention when the two halves are joined
differences = [(k, v) for k, v in sorted(manifest.items())
               if v["handwritten"] and v["draft_params"] != v["handwritten_params"]]
if manifest:
    lines += ["", "## Hand-written functions whose parameter count differs from the draft", "",
              "%d of %d. The draft's callers pass what the decompiler saw, which for register-argument functions "
              "is not always the real parameter list." % (len(differences), sum(1 for v in manifest.values() if v["handwritten"])), "",
              "| Address | Function | File | Hand-written | Draft |", "|---|---|---|---:|---:|"]
    lines += ["| %s | %s | %s | %d | %d |" % (k, v["name"], v["file"], v["handwritten_params"], v["draft_params"]) for k, v in differences]
open(os.path.join(ROOT, "PROGRESS.md"), "w").write("\n".join(lines) + "\n")
print([l for l in lines if l.startswith("| **Total**")][0])
print("parameter-count differences between src/ and the draft: %d" % len(differences) if manifest else "")
print("source files with functions:", sum(1 for b in rows if not b.startswith("(")))
