#!/usr/bin/env python3
"""Generate the do-nothing layer for the native Linux debug build of the draft.

    draft/build/ILB_draft_decls.h, ILB_draft_types.h  ->  draft/build/native/generated_stubs.c

1. Every imported function (Windows API, SDL2, FMOD, C runtime specials) gets a weak definition that
   returns 0, so the program links; draft/native/native_platform.c overrides the ones that must do something.
   Functions the Linux C library provides with the same meaning are left to it.
Direct3D needs nothing here: the rendering layer calls the OpenGL backend in port/ instead.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILD = os.path.join(ROOT, "draft", "build")
decls = open(os.path.join(BUILD, "ILB_draft_decls.h")).read()
types = open(os.path.join(BUILD, "ILB_draft_types.h")).read()
FROM_LIBC = {"malloc", "free", "memset", "memcpy", "floor", "roundf", "truncf", "atof", "atoi", "exit"}


def split_arguments(text):
    parts, depth, cur = [], 0, ""
    for ch in text:
        if ch == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
            continue
        depth += ch in "(["
        depth -= ch in ")]"
        cur += ch
    if cur.strip():
        parts.append(cur.strip())
    return parts


out = ["// Generated by tools/native_stubs.py for the native Linux debug build. Do not edit.",
       '#include "ILB_draft_decls.h"', "void *calloc( size_t, size_t );", ""]

# ---- 1. imports
import json
names, missing = [], []
for entry in json.load(open(os.path.join(ROOT, "dump", "imports.json"))):
    name = entry["name"]
    if name.startswith("?"):                # C++ import: ?stop@ChannelControl@FMOD@@... -> FMOD__ChannelControl__stop
        name = "__".join(reversed(name[1:].split("@@")[0].split("@")))
    found = None
    for spelling in (name, name.lstrip("_"), "_" + name.lstrip("_")):       # IDA drops leading underscores
        found = re.search(r"^(?!//|#|typedef)([^\n;(]*?)\b(%s)\(([^\n;]*)\);" % re.escape(spelling), decls, re.M)
        if found:
            break
    if not found:
        missing.append(name)
        continue
    head, name, params = found.group(1).strip(), found.group(2), found.group(3)
    if name in FROM_LIBC or name in names:
        continue
    returns_void = re.match(r"^(?:\w+ )*void(?: __\w+)?$", head) is not None
    stub = "__attribute__((weak)) %s %s(%s) { %s }" % (head, name, params, "" if returns_void else "return 0;")
    if name.startswith("SDL_"):         # the window build links the real SDL2
        stub = "#ifndef ILB_WINDOW\n%s\n#endif" % stub
    out.append(stub)
    names.append(name)
print("imports with no prototype in the draft (not called by game code):", ", ".join(missing))

os.makedirs(os.path.join(BUILD, "native"), exist_ok=True)
open(os.path.join(BUILD, "native", "generated_stubs.c"), "w").write("\n".join(out) + "\n")
print("%d imported functions stubbed" % len(names))
