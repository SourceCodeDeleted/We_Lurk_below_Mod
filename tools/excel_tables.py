#!/usr/bin/env python3
"""Wave 3: recover the *_definition_data structs from the excel parse tables in ILB.exe's .data section.

Descriptor (excel_parse_table), 0xA8 bytes:
    +0x00 char txt_file[64]      "xls\\items.txt"
    +0x40 char gbe_file[64]      "xls\\items.gbe"
    +0x8C column list pointer    +0x90 column count
    +0x9C pointer to the global holding the record array
    +0xA0 record size            +0xA4 pointer to the global holding the record count
Column (0x50 bytes): char name[64]; int type; int offset; int arg; int link.
Writes db/excel_tables.json, db/definitions.h and db/definitions_check.inc.
"""
import json
import os
import re
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXE = os.path.join(ROOT, "ida", "ILB.exe")
data = open(EXE, "rb").read()

pe = struct.unpack_from("<I", data, 0x3C)[0]
nsec = struct.unpack_from("<H", data, pe + 6)[0]
sec_off = pe + 24 + struct.unpack_from("<H", data, pe + 20)[0]
BASE = struct.unpack_from("<I", data, pe + 24 + 28)[0]
sections = []
for i in range(nsec):
    name, vsize, va, rsize, roff = struct.unpack_from("<8sIIII", data, sec_off + 40 * i)
    sections.append((name.rstrip(b"\0").decode(), BASE + va, vsize, roff, rsize))


def off(va):
    for _, start, _, roff, rsize in sections:
        if start <= va < start + rsize:
            return roff + va - start
    return None


def va_of(o):
    for _, start, _, roff, rsize in sections:
        if roff <= o < roff + rsize:
            return start + o - roff
    return None


def cstr(o, limit=64):
    raw = data[o:o + limit]
    return raw[:raw.index(b"\0")].decode("ascii", "replace") if b"\0" in raw else None


# Column types as stored in the table; meanings are from read_data_excel_file (ec_excel.cpp).
TYPES = {0: "safestring", 1: "name", 2: "char", 3: "int", 4: "float", 5: "byte", 6: "flag", 7: "bool",
         8: "link", 10: "int64"}
SIZES = {0: 2052, 1: 64, 2: 1, 3: 4, 4: 4, 5: 1, 6: 4, 7: 1, 8: 4, 10: 8}
CDECL = {"safestring": "safestring", "char": "char", "int": "int", "float": "float", "byte": "byte",
         "flag": "dword", "bool": "bool", "link": "int", "int64": "__int64"}


def singular(stem):
    for suffix, repl in (("classes", "class"), ("ies", "y"), ("s", "")):
        if stem.endswith(suffix):
            return stem[:len(stem) - len(suffix)] + repl
    return stem


tables = []
for m in re.finditer(rb"xls\\([a-z_0-9]+)\.txt\0", data):
    o = m.start()
    gbe = cstr(o + 0x40)
    if not gbe or not gbe.endswith(".gbe"):
        continue
    cols_va, ncols = struct.unpack_from("<II", data, o + 0x8C)
    defs_va, rec_size, count_va = struct.unpack_from("<III", data, o + 0x9C)
    if off(cols_va) is None or not 0 < ncols < 512:
        continue
    cols = []
    for i in range(ncols):
        co = off(cols_va) + 0x50 * i
        ctype, coff, arg, link = struct.unpack_from("<IIII", data, co + 64)
        cols.append({"column": cstr(co), "type": TYPES.get(ctype, "type%d" % ctype), "type_id": ctype,
                     "offset": coff, "arg": arg, "link": link})
    stem = m.group(1).decode()
    tables.append({"table": stem, "txt": cstr(o), "gbe": gbe, "descriptor": va_of(o), "columns_va": cols_va,
                   "definitions_global": defs_va, "count_global": count_va, "record_size": rec_size,
                   "struct": singular(stem) + "_definition_data", "columns": cols})

by_defs = {t["definitions_global"]: t for t in tables}
for t in tables:
    for c in t["columns"]:
        if c["type"] == "link":
            target = by_defs.get(c["link"])
            c["link_table"] = target["table"] if target else None

os.makedirs(os.path.join(ROOT, "db"), exist_ok=True)
json.dump(tables, open(os.path.join(ROOT, "db", "excel_tables.json"), "w"), indent=1)


def ident(name):
    name = re.sub(r"[^A-Za-z0-9_]", "_", name.strip()).lower()
    return ("_" + name) if name[:1].isdigit() else name


out = ["// Generated by tools/excel_tables.py from the excel parse tables in ILB.exe. Do not edit by hand.",
       "// Field names are the spreadsheet column names; the original C field names can differ",
       "// (the 2019 source maps column \"atk_rate\" to field attack_rate, \"gold_cost\" to cost).",
       "// unknown_* members are bytes no column writes: fields filled in by code, or padding.",
       "", "#pragma once", ""]
for t in tables:
    cols = sorted(t["columns"], key=lambda c: c["offset"])
    out.append("// xls\\%s.txt, %d columns, records at 0x%X, count at 0x%X" % (
        t["table"], len(cols), t["definitions_global"], t["count_global"]))
    out.append("struct %s   // sizeof 0x%X (%d)" % (t["struct"], t["record_size"], t["record_size"]))
    out.append("{")
    pos = 0
    used = set()
    for i, c in enumerate(cols):
        nxt = cols[i + 1]["offset"] if i + 1 < len(cols) else t["record_size"]
        if c["offset"] < pos:
            out.append("    // column \"%s\" (%s) also maps to offset 0x%X" % (c["column"], c["type"], c["offset"]))
            continue
        if c["offset"] > pos:
            out.append("    byte        unknown_%X[%d];" % (pos, c["offset"] - pos))
        name = ident(c["column"])
        while name in used:
            name += "_"
        used.add(name)
        size = SIZES.get(c["type_id"])
        if c["type"] == "name":
            decl = "char        %s[%d];" % (name, size)
        elif c["type"] in CDECL:
            decl = "%-11s %s;" % (CDECL[c["type"]], name)
        else:
            size = nxt - c["offset"]
            decl = "byte        %s[%d];" % (name, size)
        note = "0x%03X" % c["offset"]
        if c["type"] == "link":
            note += "  index into %s (record size %d)" % (c.get("link_table") or hex(c["link"]), c["arg"])
        elif c["type"] == "flag":
            note += "  bit %d" % c["arg"]
        elif c["type"] not in CDECL and c["type"] != "name":
            note += "  excel type %d, meaning not known" % c["type_id"]
        elif c["arg"]:
            note += "  arg %d" % c["arg"]
        out.append("    %-44s // %s" % (decl, note))
        pos = c["offset"] + size
    if pos < t["record_size"]:
        out.append("    byte        unknown_%X[%d];" % (pos, t["record_size"] - pos))
    elif pos > t["record_size"]:
        out.append("    // WARNING: columns run past the record size")
    out.append("};")
    out.append("")
open(os.path.join(ROOT, "db", "definitions.h"), "w").write("\n".join(out))

with open(os.path.join(ROOT, "db", "definitions_check.inc"), "w") as f:
    f.write("// Generated by tools/excel_tables.py: record sizes stored in the exe's table descriptors.\n")
    for t in tables:
        f.write("SIZE(%s, %d);\n" % (t["struct"], t["record_size"]))

print("%d tables, %d columns" % (len(tables), sum(len(t["columns"]) for t in tables)))
for t in tables:
    kinds = sorted({c["type"] for c in t["columns"]})
    print("  %-18s %3d cols  record %5d  defs 0x%X  %s" % (
        t["table"], len(t["columns"]), t["record_size"], t["definitions_global"], ",".join(kinds)))
