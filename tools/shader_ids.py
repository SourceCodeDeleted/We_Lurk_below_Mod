#!/usr/bin/env python3
"""Write port/gge_gl_shader_ids.h: how the OpenGL backend recognises each of the game's compiled shaders.

The game loads "<name>.vso" / "<name>.pso" from the pack file and hands over only the bytes; the backend
picks its GLSL program by a hash of those bytes. Run again if the pack file's shaders ever change.
"""
import glob
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
lines = ["// Generated by tools/shader_ids.py from dump/gbp/shaders/dx11. Do not edit.",
         "// FNV-1a hash of the compiled shader, its size, pixel shader (1) or vertex shader (0), name.",
         "static const struct { unsigned int hash, size; int pixel; const char *name; } gge_gl_shader_ids[] =", "{"]
for path in sorted(glob.glob(os.path.join(ROOT, "dump", "gbp", "shaders", "dx11", "*.?so"))):
    data = open(path, "rb").read()
    h = 0x811C9DC5
    for byte in data:
        h = ((h ^ byte) * 0x01000193) & 0xFFFFFFFF
    name, ext = os.path.splitext(os.path.basename(path))
    lines.append('    { 0x%08Xu, %d, %d, "%s" },' % (h, len(data), ext == ".pso", name))
lines += ["};", ""]
open(os.path.join(ROOT, "port", "gge_gl_shader_ids.h"), "w").write("\n".join(lines))
print("%d shaders" % (len(lines) - 6))
