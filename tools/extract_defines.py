#!/usr/bin/env python3
"""Collect the #define constants transcribed from the 2019 source (README.MD code blocks) into db/defines.h.
These are 2019 values: flags added after that are missing, so treat an unlisted bit as unknown, not unused."""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
text = open(os.path.join(ROOT, "README.MD")).read()
lines = ["// Generated by tools/extract_defines.py from the 2019 source transcribed in README.MD.", "",
         "#pragma once", ""]
seen = set()
for block in re.findall(r"```c\n(.*?)```", text, re.S):
    for line in block.splitlines():
        m = re.match(r"#define\s+(\w+)\s+(.+?)\s*(//.*)?$", line)
        if not m or m.group(1) in seen or "off screen" in line or m.group(1).startswith("_"):
            continue
        seen.add(m.group(1))
        lines.append("#define %-40s %s" % (m.group(1), m.group(2).strip()))
open(os.path.join(ROOT, "db", "defines.h"), "w").write("\n".join(lines) + "\n")
print("defines: %d" % len(seen))
