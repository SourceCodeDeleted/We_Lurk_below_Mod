#!/usr/bin/env python3
"""Decode the unpacked xls/*.gbe tables (raw arrays of *_definition_data) with the layouts in
db/excel_tables.json. Writes dump/tables/<table>.tsv and db/enums.h (row-name enums per table).

Usage: gbe_dump.py   (expects tools/gbp_unpack.py --extract dump/gbp to have been run)
"""
import csv
import json
import os
import re
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tables = json.load(open(os.path.join(ROOT, "db", "excel_tables.json")))
out_dir = os.path.join(ROOT, "dump", "tables")
os.makedirs(out_dir, exist_ok=True)

# Enum prefix per table: the code's own names where an assert or the 2019 source shows them, else the stem.
PREFIX = {"items": "item_type", "objects": "object_type", "monsters": "monster_type", "sounds": "sound",
          "missiles": "missile_type", "tiles": "rlg_tile", "damage_types": "damage_type",
          "equipment_slots": "equipment_slot", "strings": "string_token", "emitters": "emitter_type"}

rows_by_table = {}
for t in tables:
    path = os.path.join(ROOT, "dump", "gbp", "xls", t["table"] + ".gbe")
    if not os.path.exists(path):
        continue
    blob = open(path, "rb").read()
    size = t["record_size"]
    assert len(blob) % size == 0, t["table"]
    cols = sorted(t["columns"], key=lambda c: c["offset"])
    rows = []
    for r in range(len(blob) // size):
        rec = blob[r * size:(r + 1) * size]
        row = [r]
        for i, c in enumerate(cols):
            o = c["offset"]
            if c["type"] == "name":
                row.append(rec[o:o + 64].split(b"\0", 1)[0].decode("latin-1"))
            elif c["type"] == "safestring":
                length = struct.unpack_from("<i", rec, o)[0]
                row.append(rec[o + 4:o + 4 + 2 * length].decode("utf-16-le", "replace"))
            elif c["type"] == "int64":
                row.append(struct.unpack_from("<q", rec, o)[0])
            elif c["type"] in ("byte", "char"):
                row.append(rec[o])
            elif c["type"] == "float":
                row.append("%g" % struct.unpack_from("<f", rec, o)[0])
            elif c["type"] == "bool":
                row.append(rec[o])
            else:
                row.append(struct.unpack_from("<i", rec, o)[0])
        rows.append(row)
    rows_by_table[t["table"]] = (cols, rows)
    with open(os.path.join(out_dir, t["table"] + ".tsv"), "w", newline="") as f:
        w = csv.writer(f, delimiter="\t")
        w.writerow(["#"] + [c["column"] for c in cols])
        w.writerows(rows)

# strings ship as text, not .gbe
strings_path = os.path.join(ROOT, "dump", "gbp", "xls", "strings.txt")
string_rows = []
if os.path.exists(strings_path):
    for line in open(strings_path, encoding="latin-1", newline="").read().split("\r\n")[1:]:
        parts = line.split("\t")
        if len(parts) >= 2 and parts[0] and parts[1].strip().isdigit():
            string_rows.append((parts[0], int(parts[1])))

out = ["// Generated by tools/gbe_dump.py from the tables inside ILB.gbp. Do not edit by hand.",
       "// Enum prefixes for items, objects and strings are the ones the game's source uses",
       "// (item_type_adamantine_pickaxe, object_type_mushroom_bl_red, string_token_mushroom_brown);",
       "// the other prefixes are the table name and may differ from the original.", "", "#pragma once", ""]
for t in tables:
    if t["table"] not in rows_by_table:
        continue
    cols, rows = rows_by_table[t["table"]]
    if cols[0]["type"] != "name":
        continue
    prefix = PREFIX.get(t["table"], t["struct"][:-len("_definition_data")])
    out.append("enum %s_id   // xls\\%s.txt row order" % (prefix, t["table"]))
    out.append("{")
    seen = set()
    for row in rows:
        name = re.sub(r"[^A-Za-z0-9_]", "_", row[1]).lower()
        if not name:
            continue
        ident = "%s_%s" % (prefix, name)
        if ident in seen:
            ident += "_%d" % row[0]
        seen.add(ident)
        out.append("    %s = %d," % (ident, row[0]))
    out.append("    num_%s_rows = %d" % (prefix, len(rows)))
    out.append("};")
    out.append("")
if string_rows:
    out.append("enum string_token_id   // xls\\strings.txt, value is the id column")
    out.append("{")
    seen = set()
    for token, sid in string_rows:
        ident = "string_token_" + re.sub(r"[^A-Za-z0-9_]", "_", token)
        if ident in seen:
            continue
        seen.add(ident)
        out.append("    %s = %d," % (ident, sid))
    out[-1] = out[-1].rstrip(",")
    out.append("};")
    out.append("")
open(os.path.join(ROOT, "db", "enums.h"), "w").write("\n".join(out))
print("tables decoded: %d, string tokens: %d" % (len(rows_by_table), len(string_rows)))
for name, (cols, rows) in rows_by_table.items():
    print("  %-18s %5d rows" % (name, len(rows)))
